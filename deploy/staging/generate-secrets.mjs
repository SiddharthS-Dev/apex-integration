#!/usr/bin/env node
/**
 * Writes deploy/staging/.env.staging (gitignored, mode 0600) with fresh random secrets for the
 * private staging stack (compose.yml). Node built-ins only.
 *
 *   node deploy/staging/generate-secrets.mjs                     create; refuses to overwrite
 *   node deploy/staging/generate-secrets.mjs --force             create anew (every secret changes:
 *                                                                the databases must be recreated too)
 *   node deploy/staging/generate-secrets.mjs --rotate-identity-keys   new current kid, previous kept
 *   node deploy/staging/generate-secrets.mjs --prune-identity-keys    drop every kid but the current
 *   options: --out <file>   --port <n>   --admin-email <e>
 *
 * Rotation and pruning rewrite only the identity-key lines and keep every other value; the old file
 * is kept beside it as .env.staging.bak-<time>. After either, restart the whole stack (keys are read
 * at start-up only): see docs/operations/STAGING_RUNBOOK.md.
 *
 * Every value is throwaway and local to this machine or CI run. Nothing here is a real credential;
 * nothing is printed except variable names and the key id.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { AUDIENCES, keysFor, validateStore } from '../../apex/identity-keys.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
export const DEFAULT_OUT = path.join(HERE, '.env.staging')

const hex = (n) => crypto.randomBytes(n).toString('hex')
const b64 = (n) => crypto.randomBytes(n).toString('base64')
const b64url = (n) => crypto.randomBytes(n).toString('base64url')

const newKid = () => `k${new Date().toISOString().slice(0, 10).replace(/-/g, '')}${hex(4)}`
const newKeySet = () => Object.fromEntries(AUDIENCES.map((a) => [a, b64(32)]))

/** A fresh identity key store, in apex/.identity-keys.json's format. */
export function newStore() {
  const kid = newKid()
  return validateStore({ current: kid, keys: { [kid]: newKeySet() } })
}

/** A new current kid; the one it replaces is kept for overlap, anything older dropped (as identity-keys.mjs rotate). */
export function rotateStore(store) {
  validateStore(store)
  let kid = newKid()
  while (store.keys[kid]) kid = newKid()
  return validateStore({ current: kid, keys: { [store.current]: store.keys[store.current], [kid]: newKeySet() } })
}

/** Only the current kid (as identity-keys.mjs prune). */
export function pruneStore(store) {
  validateStore(store)
  return validateStore({ current: store.current, keys: { [store.current]: store.keys[store.current] } })
}

/** The identity variables compose.yml reads: the whole store for the gateway, one audience per service. */
export function identityVars(store) {
  return {
    APEX_IDENTITY_KID: store.current,
    APEX_IDENTITY_KEYS_STORE: JSON.stringify(store),
    APEX_IDENTITY_KEYS_CORE: JSON.stringify(keysFor(store, 'core')),
    APEX_IDENTITY_KEYS_SHOWCASE: JSON.stringify(keysFor(store, 'showcase')),
    APEX_IDENTITY_KEYS_SLIDESVAULT: JSON.stringify(keysFor(store, 'slidesvault')),
  }
}

/** Every variable, freshly generated. */
export function freshVars({ port = 4173, adminEmail = 'staging-admin@apex-staging.invalid' } = {}) {
  return {
    APEX_STAGING_PORT: String(port),
    APEX_PUBLIC_URL: `http://localhost:${port}`,
    APEX_IMAGE_TAG: 'local',
    POSTGRES_PASSWORD: hex(24),
    CORE_DB_PASSWORD: hex(24),
    SHOWCASE_DB_PASSWORD: hex(24),
    SLIDESVAULT_DB_PASSWORD: hex(24),
    BOOTSTRAP_ADMIN_EMAIL: adminEmail,
    BOOTSTRAP_ADMIN_PASSWORD: b64url(24),
    BOOTSTRAP_ADMIN_NAME: 'Staging Test Admin',
    CORE_TOKEN_ENCRYPTION_KEY: b64(32),
    SHOWCASE_ENCRYPTION_KEY: hex(32),
    SLIDESVAULT_TOKEN_ENCRYPTION_KEY: b64(32),
    ...identityVars(newStore()),
  }
}

/**
 * KEY=VALUE lines as docker compose reads an --env-file. JSON values are single-quoted (literal in
 * compose); nothing generated here contains a single quote, a `$` or a newline.
 */
export function serialise(vars) {
  const lines = [
    '# APEX private staging secrets. Generated by deploy/staging/generate-secrets.mjs.',
    '# Throwaway values for this machine or CI run only. Never commit, never copy into chat or tickets.',
    `# Generated ${new Date().toISOString()}. Variable reference: .env.staging.example`,
  ]
  for (const [k, v] of Object.entries(vars)) {
    const s = String(v)
    if (/['\n$]/.test(s)) throw new Error(`${k}: value cannot be written safely`)
    lines.push(`${k}=${/^[A-Za-z0-9_.:/@+=-]*$/.test(s) ? s : `'${s}'`}`)
  }
  return `${lines.join('\n')}\n`
}

/** Parses what serialise() writes (and simple hand edits): KEY=VALUE, optional single or double quotes. */
export function parseEnv(text) {
  const out = {}
  for (const raw of String(text).split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq < 1) continue
    let value = line.slice(eq + 1).trim()
    if (value.length >= 2 && ((value[0] === "'" && value.endsWith("'")) || (value[0] === '"' && value.endsWith('"')))) value = value.slice(1, -1)
    out[line.slice(0, eq).trim()] = value
  }
  return out
}

function writeSecure(file, text) {
  const tmp = `${file}.${process.pid}.tmp`
  fs.writeFileSync(tmp, text, { mode: 0o600 })
  fs.renameSync(tmp, file)
  try {
    fs.chmodSync(file, 0o600)
  } catch {
    /* Windows ignores modes */
  }
}

function main(argv) {
  const arg = (name) => {
    const i = argv.indexOf(name)
    return i >= 0 ? argv[i + 1] : undefined
  }
  const out = path.resolve(arg('--out') || DEFAULT_OUT)
  const rotating = argv.includes('--rotate-identity-keys')
  const pruning = argv.includes('--prune-identity-keys')

  if (rotating || pruning) {
    if (!fs.existsSync(out)) throw new Error(`${out} does not exist — generate it first.`)
    const vars = parseEnv(fs.readFileSync(out, 'utf8'))
    const store = validateStore(JSON.parse(vars.APEX_IDENTITY_KEYS_STORE || 'null'))
    const next = rotating ? rotateStore(store) : pruneStore(store)
    const backup = `${out}.bak-${new Date().toISOString().replace(/[:.]/g, '-')}`
    fs.copyFileSync(out, backup)
    try {
      fs.chmodSync(backup, 0o600)
    } catch {
      /* Windows */
    }
    writeSecure(out, serialise({ ...vars, ...identityVars(next) }))
    console.log(`  ${rotating ? 'Rotated' : 'Pruned'} identity keys in ${out}`)
    console.log(`  current kid ${next.current}; kids now: ${Object.keys(next.keys).join(', ')}`)
    console.log(`  previous file kept as ${backup}`)
    console.log('  Restart the whole stack now (compose up -d --force-recreate): keys are read at start-up only.')
    return
  }

  if (fs.existsSync(out) && !argv.includes('--force')) {
    throw new Error(`${out} already exists. Use --force to replace every secret (then recreate the volumes: down -v).`)
  }
  const port = Number(arg('--port') || 4173)
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('--port must be a TCP port')
  const vars = freshVars({ port, adminEmail: arg('--admin-email') || undefined })
  fs.mkdirSync(path.dirname(out), { recursive: true })
  writeSecure(out, serialise(vars))
  console.log(`  Wrote ${out} (mode 0600) with ${Object.keys(vars).length} variables; identity kid ${vars.APEX_IDENTITY_KID}.`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    main(process.argv.slice(2))
  } catch (error) {
    console.error(`  generate-secrets: ${error.message}`)
    process.exit(1)
  }
}
