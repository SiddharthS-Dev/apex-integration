/**
 * The offline service worker, hand-written and generated at build time.
 *
 * `serviceWorkerPlugin()` (used by vite.config.js) emits `<base>sw.js` into the
 * build with the exact list of files Vite produced, so the app shell — the
 * HTML, every JS/CSS chunk, the icon and the manifest — is cached on install
 * and the app opens with no network. The infographics (~48 MB) are not
 * precached; plates saved for offline live in IndexedDB (offlineStore.js).
 *
 * Routing, for same-origin GETs inside the app's base path:
 *   navigations   network first, falling back to the cached index.html
 *   <base>api/…   network first; JSON answers (not /api/auth/*) are kept so the
 *                 catalogue still lists offline; the page clears that cache on
 *                 sign-out (registerServiceWorker.js)
 *   everything    cache first (hashed, immutable), then network
 *   else
 * Nothing outside the base path, nothing cross-origin, nothing but GET.
 */

/** @param {{ base: string, precache: string[], version: string }} opts */
export function serviceWorkerSource({ base, precache, version }) {
  const config = JSON.stringify({ base, precache: [...new Set(precache)].map((f) => base + f), version })
  return `/* generated by scripts/serviceWorker.mjs — do not edit */
const CONFIG = ${config}
const SHELL = 'insp-shell-' + CONFIG.version
const API = 'insp-api'
const INDEX = CONFIG.base + 'index.html'

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(CONFIG.precache)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('insp-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  )
})

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'clear-api-cache') event.waitUntil(caches.delete(API))
})

async function networkFirst(request, cacheName, keep) {
  try {
    const res = await fetch(request)
    if (keep(res)) {
      const copy = res.clone()
      caches.open(cacheName).then((c) => c.put(request, copy)).catch(() => {})
    }
    return res
  } catch (error) {
    const hit = await caches.match(request, { cacheName })
    if (hit) return hit
    throw error
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin || !url.pathname.startsWith(CONFIG.base)) return

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => caches.match(INDEX, { cacheName: SHELL }).then((hit) => hit || Response.error()))
    )
    return
  }
  if (url.pathname.startsWith(CONFIG.base + 'api/')) {
    if (url.pathname.startsWith(CONFIG.base + 'api/auth/')) return
    const json = (res) => res.ok && (res.headers.get('content-type') || '').includes('application/json')
    event.respondWith(networkFirst(request, API, json))
    return
  }
  event.respondWith(caches.match(request, { cacheName: SHELL }).then((hit) => hit || fetch(request)))
})
`
}

/** Files from the build worth precaching: the shell, not the image library. */
export const isShellFile = (fileName) => /\.(js|css|html|svg|webmanifest)$/.test(fileName) && !fileName.startsWith('images/')

/** Vite plugin: emit sw.js for production builds. Public files are listed by name. */
export function serviceWorkerPlugin({ publicFiles = ['favicon.svg', 'manifest.webmanifest'] } = {}) {
  let base = '/'
  return {
    name: 'inspironics-service-worker',
    apply: 'build',
    enforce: 'post',
    configResolved(config) {
      base = config.base
    },
    generateBundle(_options, bundle) {
      const built = Object.keys(bundle).filter(isShellFile)
      const precache = ['index.html', ...built.filter((f) => f !== 'index.html'), ...publicFiles]
      // the version changes whenever any built file does (their names are content hashes)
      let h = 0
      for (const ch of built.sort().join('|')) h = (h * 31 + ch.charCodeAt(0)) | 0
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorkerSource({ base, precache, version: (h >>> 0).toString(36) }) })
    },
  }
}
